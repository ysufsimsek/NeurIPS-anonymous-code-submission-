@torch.inference_mode()
def logprob_continuation(prompt: str, continuation: str):
    """
    Returns: sum_logp, mean_logp, n_tokens, prefix_ok
    Scores EXACT prompt+continuation.
    """
    prompt2, cont2 = _shift_trailing_ws(prompt, continuation)
    full = prompt2 + cont2

    enc_full = tokenizer(full, return_tensors="pt", add_special_tokens=False)
    enc_prompt = tokenizer(prompt2, return_tensors="pt", add_special_tokens=False)

    full_ids = enc_full.input_ids[0]
    prompt_ids = enc_prompt.input_ids[0]
    prefix_ok = bool(torch.equal(full_ids[:len(prompt_ids)], prompt_ids))

    prompt_len = len(prompt_ids)
    cont_ids = full_ids[prompt_len:]
    n = len(cont_ids)
    if n == 0 or prompt_len == 0:
        return float("-inf"), float("-inf"), 0, prefix_ok

    input_ids = enc_full.input_ids.to(MODEL_DEVICE)
    attention_mask = enc_full.attention_mask.to(MODEL_DEVICE)

    logits = model(input_ids=input_ids, attention_mask=attention_mask, use_cache=False).logits[0]
    logprobs = F.log_softmax(logits, dim=-1)

    start = prompt_len - 1
    end = start + n
    lp_slice = logprobs[start:end]

    cont_ids_dev = cont_ids.to(MODEL_DEVICE)
    token_logps = lp_slice.gather(1, cont_ids_dev.unsqueeze(1)).squeeze(1)

    sum_logp = float(token_logps.sum().item())
    mean_logp = sum_logp / n
    return sum_logp, mean_logp, n, prefix_ok

def score_item(prompt_left: str, suffix_right: str, cand_di: str, cand_mis: str):
    """
    c: candidate-only (primary)
    f: candidate+suffix with leading punctuation removed (robustness)
    """
    di_ins = insert_candidate(prompt_left, cand_di)
    mis_ins = insert_candidate(prompt_left, cand_mis)

    # c) candidate-only
    di_c_sum, di_c_mean, di_c_n, di_c_ok = logprob_continuation(prompt_left, di_ins)
    mi_c_sum, mi_c_mean, mi_c_n, mi_c_ok = logprob_continuation(prompt_left, mis_ins)

    # f) candidate + suffix (no leading punctuation)
    suffix_stripped = strip_leading_punct(suffix_right)
    di_full = attach_suffix_no_punct(di_ins, suffix_right)
    mi_full = attach_suffix_no_punct(mis_ins, suffix_right)

    di_f_sum, di_f_mean, di_f_n, di_f_ok = logprob_continuation(prompt_left, di_full)
    mi_f_sum, mi_f_mean, mi_f_n, mi_f_ok = logprob_continuation(prompt_left, mi_full)

    delta_c_mean = di_c_mean - mi_c_mean
    delta_f_mean = di_f_mean - mi_f_mean

    return {
        "Used_Insert_DI": di_ins,
        "Used_Insert_MIS": mis_ins,
        "suffix_right_stripped": suffix_stripped,

        "di_c_sum": di_c_sum, "di_c_mean": di_c_mean, "di_c_n_tok": di_c_n, "di_c_prefix_ok": di_c_ok,
        "mis_c_sum": mi_c_sum, "mis_c_mean": mi_c_mean, "mis_c_n_tok": mi_c_n, "mis_c_prefix_ok": mi_c_ok,
        "delta_c_sum": di_c_sum - mi_c_sum,
        "delta_c_mean": delta_c_mean,
        "choice_c_mean": choice_from_delta(delta_c_mean),

        "di_f_sum": di_f_sum, "di_f_mean": di_f_mean, "di_f_n_tok": di_f_n, "di_f_prefix_ok": di_f_ok,
        "mis_f_sum": mi_f_sum, "mis_f_mean": mi_f_mean, "mis_f_n_tok": mi_f_n, "mis_f_prefix_ok": mi_f_ok,
        "delta_f_sum": di_f_sum - mi_f_sum,
        "delta_f_mean": delta_f_mean,
        "choice_f_mean": choice_from_delta(delta_f_mean),
    }


