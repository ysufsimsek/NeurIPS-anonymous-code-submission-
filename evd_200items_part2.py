@torch.inference_mode()
def logprob_continuation(prompt: str, continuation: str):
    """
    Returns: sum_logp, mean_logp, n_tokens, prefix_ok
    Scores EXACT prompt+continuation.
    """
    prompt2, cont2 = _shift_trailing_ws(prompt, continuation)
    full = prompt2 + cont2

    enc_full = tokenizer(full, return_tensors="pt", add_special_tokens=False)
    enc_prompt = tokenizer(prompt2, return_tensors="pt", add_special_tokens=False)

    full_ids = enc_full.input_ids[0]
    prompt_ids = enc_prompt.input_ids[0]
    prefix_ok = bool(torch.equal(full_ids[:len(prompt_ids)], prompt_ids))

    prompt_len = len(prompt_ids)
    cont_ids = full_ids[prompt_len:]
    n = len(cont_ids)
    if n == 0 or prompt_len == 0:
        return float("-inf"), float("-inf"), 0, prefix_ok

    input_ids = enc_full.input_ids.to(MODEL_DEVICE)
    attention_mask = enc_full.attention_mask.to(MODEL_DEVICE)

    logits = model(input_ids=input_ids, attention_mask=attention_mask, use_cache=False).logits[0]
    logprobs = F.log_softmax(logits, dim=-1)

    start = prompt_len - 1
    end = start + n
    lp_slice = logprobs[start:end]

    cont_ids_dev = cont_ids.to(MODEL_DEVICE)
    token_logps = lp_slice.gather(1, cont_ids_dev.unsqueeze(1)).squeeze(1)

    sum_logp = float(token_logps.sum().item())
    mean_logp = sum_logp / n
    return sum_logp, mean_logp, n, prefix_ok

