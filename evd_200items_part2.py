def split_on_blank(sentence: str):
    s = str(sentence)
    m = re.search(r"_{2,}", s)
    if not m:
        return None, None
    return s[:m.start()], s[m.end():]

def _clean_last_word(pre_text: str) -> str:
    clean = re.sub(r"[^\w\s]", "", str(pre_text)).strip()
    if not clean:
        return ""
    return clean.split()[-1].lower()

def get_candidates_from_verbmap(prompt_left: str):
    last_word = _clean_last_word(prompt_left)
    if last_word in VERB_MAP:
        c1, c2 = VERB_MAP[last_word]
        return c1, c2, last_word, True
    return "edildi", "edilmiş", last_word, False

def insert_candidate(prompt_left: str, candidate: str) -> str:
    candidate = str(candidate).strip()
    if prompt_left and not prompt_left.endswith((" ", "\t", "\n")):
        return " " + candidate
    return candidate

def choice_from_delta(delta: float) -> str:
    if delta > 0: return "DI"
    if delta < 0: return "MIŞ"
    return "TIE"

def _shift_trailing_ws(prompt: str, continuation: str):
    m = re.search(r"\s*$", prompt)
    trail = m.group(0) if m else ""
    if trail:
        return prompt[:-len(trail)], trail + continuation
    return prompt, continuation

def strip_leading_punct(s: str) -> str:
    return re.sub(r"^\s*[.?!,;:]+\s*", "", str(s))

def attach_suffix_no_punct(continuation: str, suffix_right: str) -> str:
    suf = strip_leading_punct(suffix_right).strip()
    if not suf:
        return continuation
    return continuation + " " + suf


